#!/usr/bin/env node
// Turns the supplied flavour artwork into alpha masks the page can tint.
//
// The originals are ~1400px and up to 320KB each, which is absurd for something drawn at
// 16px beside a bar. They are also each a fixed colour, and the bar beside the icon has to
// match it exactly; shipping them as pictures means the two are set in different places and
// drift. Exported as a mask instead, the icon takes its colour from the same CSS custom
// property the bar does, so they cannot disagree.
//
// The alpha channel is the shape. Deriving it from brightness instead would lose the Sweet
// icon completely, which is ivory on nothing.
//
// Run with --write to apply; --check exits non-zero if an output is missing or stale.

import { createHash } from 'node:crypto';
import { readdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

import { FLAVOUR_AXES } from '../public/catalogue-flavour-axes.mjs';

const outDir = new URL('../public/art/flavour/', import.meta.url);
const manifestUrl = new URL('../public/catalogue-flavour-art.mjs', import.meta.url);

// Generated, so the hashed filenames are never typed by hand and never go stale against
// what is actually on disk.
function renderManifest(entries) {
  const lines = Object.entries(entries)
    .map(([id, file]) => `  ${id}: '/art/flavour/${file}'`).join(',\n');
  return `// Generated by scripts/build-flavour-icons.mjs. Do not edit.\n`
    + `//\n`
    + `// Each mask is named for a hash of its own contents, because /art/* is served\n`
    + `// immutable. Re-run the build after changing any flavour artwork.\n`
    + `export const FLAVOUR_ART = Object.freeze({\n${lines}\n});\n`;
}
export const MASK_SIZE = 128;

// Every mask is drawn at the same height so the icons sit on a common baseline; a tall
// narrow one and a squat wide one must not end up optically different sizes.
export async function buildMask(sourcePath) {
  const trimmed = await sharp(sourcePath).ensureAlpha().trim({ threshold: 1 }).toBuffer();
  const { data, info } = await sharp(trimmed)
    .resize({ width: MASK_SIZE, height: MASK_SIZE, fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .ensureAlpha().raw().toBuffer({ resolveWithObject: true });

  // Colour is discarded: the shape is carried entirely by alpha, and the page paints it.
  const mask = Buffer.alloc(info.width * info.height * 4);
  for (let i = 0; i < info.width * info.height; i++) mask[i * 4 + 3] = data[i * 4 + 3];
  return sharp(mask, { raw: { width: info.width, height: info.height, channels: 4 } })
    .png({ compressionLevel: 9, palette: false }).toBuffer();
}

// Named for its own contents, like the artwork and the stylesheet beside it. /art/* is
// served immutable, so a mask under a fixed name could never be corrected in a browser
// that had already cached it.
export function maskFileName(axisId, mask) {
  return `${axisId}-${createHash('sha256').update(mask).digest('hex').slice(0, 8)}.png`;
}

export async function sampleColour(sourcePath) {
  const { data, info } = await sharp(sourcePath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const buckets = new Map();
  for (let i = 0; i < info.width * info.height; i++) {
    if (data[i * 4 + 3] < 250) continue;
    const key = `${data[i * 4] >> 3},${data[i * 4 + 1] >> 3},${data[i * 4 + 2] >> 3}`;
    buckets.set(key, (buckets.get(key) || 0) + 1);
  }
  if (!buckets.size) return null;
  const top = [...buckets.entries()].sort((a, b) => b[1] - a[1])[0][0];
  const [r, g, b] = top.split(',').map(v => (Number(v) << 3) + 4);
  return '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sources = Object.fromEntries(
    process.argv.slice(2).filter(arg => arg.includes('=')).map(arg => arg.split('='))
  );
  const write = process.argv.includes('--write');
  const existing = await readdir(outDir).catch(() => []);
  const manifest = {};
  const keep = new Set();
  const missing = [];

  for (const axis of FLAVOUR_AXES) {
    const source = sources[axis.id];
    if (!source) {
      const already = existing.find(name => name.startsWith(`${axis.id}-`));
      if (already) { manifest[axis.id] = already; keep.add(already); }
      else missing.push(axis.id);
      continue;
    }
    const mask = await buildMask(source);
    const name = maskFileName(axis.id, mask);
    const colour = await sampleColour(source);
    manifest[axis.id] = name;
    keep.add(name);
    const unchanged = existing.includes(name);
    console.log(`${axis.id.padEnd(6)} ${(mask.length / 1024).toFixed(1)}KB ${name} sampled=${colour} declared=${axis.colour}${colour && colour !== axis.colour ? '  MISMATCH' : ''}${unchanged ? '  (unchanged)' : ''}`);
    if (write && !unchanged) await writeFile(new URL(name, outDir), mask);
  }

  if (write) {
    for (const stale of existing) {
      if (!keep.has(stale)) { await rm(new URL(stale, outDir)); console.log(`removed stale ${stale}`); }
    }
    await writeFile(manifestUrl, renderManifest(manifest));
    console.log(`manifest written with ${Object.keys(manifest).length} of ${FLAVOUR_AXES.length} axes`);
  }

  if (missing.length) {
    console.error(`no artwork yet for: ${missing.join(', ')}`);
    if (process.argv.includes('--check')) process.exit(1);
  }
  if (process.argv.includes('--check')) { console.log('every axis has a mask'); process.exit(0); }
  if (!write) console.log('(dry run, pass --write)');
}
